/** 그림마다 무엇인지(3D 화면 캡처인지 사진인지) 알려 주는 글. roomInfo: 평면도로 만든 방 정보 (보정한 방만, 없으면 빈 문자열) */
const SOURCE_LABEL = { capture: '3D 스캔 화면 캡처', top: '3D 스캔을 바로 위에서 내려다본 그림 (천장을 잘라 냄)', photo: '사용자가 찍은 사진' } as const;

export function analysisUserPrompt(sources: (keyof typeof SOURCE_LABEL)[], roomInfo = ''): string {
  return [
    `그림 ${sources.length}장을 보고 리포트를 써라.`,
    ...sources.map((source, index) => `그림 ${index + 1}: ${SOURCE_LABEL[source]}`),
    ...(roomInfo ? ['', '방 정보 (방 주인이 평면도에서 잰 값):', roomInfo] : []),
  ].join('\n');
}

/** 방 요약에 이전 시도에서 못 놓은 이유를 붙인다 */
export function layoutUserPrompt(roomSummary: string, problems: string[] = []): string {
  if (problems.length === 0) return roomSummary;
  return [roomSummary, '', '이전 시도의 문제 (이 가구들은 요청한 자리에 놓지 못했다):', ...problems.map((p) => `- ${p}`)].join('\n');
}
